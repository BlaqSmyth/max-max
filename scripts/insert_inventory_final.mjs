async function run() {
  const client = await pool.connect();
  try {
    // Get existing product names to avoid duplicates
    const { rows: existing } = await client.query('SELECT lower(name) as lname FROM products');
    const existingNames = new Set(existing.map(r => r.lname));
    console.log('Existing products:', existingNames.size);

    let inserted = 0, skipped = 0;
    const CHUNK = 100;

    // Filter out duplicates
    const toInsert = products.filter(([name]) => {
      if (existingNames.has(name.toLowerCase())) { skipped++; return false; }
      return true;
    });

    console.log(`To insert: ${toInsert.length}, Skipping duplicates: ${skipped}`);

    for (let i = 0; i < toInsert.length; i += CHUNK) {
      const chunk = toInsert.slice(i, i + CHUNK);
      const values = chunk.map(([name, price, category]) => ({
        id: randomUUID(),
        name,
        description: null,
        category,
        price: parseFloat(price).toFixed(2),
        member_price: null,
        image: '/placeholder-product.png',
        in_stock: 1,
      }));

      const placeholders = values.map((_, idx) =>
        `($${idx*9+1},$${idx*9+2},$${idx*9+3},$${idx*9+4},$${idx*9+5},$${idx*9+6},$${idx*9+7},$${idx*9+8},$${idx*9+9})`
      ).join(',');

      const flat = values.flatMap(v => [v.id, v.name, v.description, v.category, v.price, v.member_price, v.image, v.in_stock, null]);

      await client.query(
        `INSERT INTO products (id, name, description, category, price, member_price, image, in_stock, epos_code)
         VALUES ${placeholders}
         ON CONFLICT (id) DO NOTHING`,
        flat
      );
      inserted += chunk.length;
      process.stdout.write(`\rInserted: ${inserted}/${toInsert.length}`);
    }

    const { rows: final } = await client.query('SELECT count(*) FROM products');
    console.log(`\nDone! Total products now: ${final[0].count}`);

  } finally {
    client.release();
    await pool.end();
  }
}

