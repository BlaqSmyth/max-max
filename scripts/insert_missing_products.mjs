// Insert in batches of 200
async function insertBatch(batch) {
  const { data, error } = await supabase.from('products').upsert(batch, { onConflict: 'id' });
  if (error) {
    console.error('Batch error:', error.message);
    return 0;
  }
  return batch.length;
}

async function main() {
  let total = 0;
  const batchSize = 200;
  for (let i = 0; i < allProducts.length; i += batchSize) {
    const batch = allProducts.slice(i, i + batchSize);
    const count = await insertBatch(batch);
    total += count;
    console.log(`Inserted batch ${Math.floor(i / batchSize) + 1}: ${count} products (running total: ${total})`);
  }
  console.log(`\nDone! Inserted ${total} new products.`);

  // Verify new total
  const { count } = await supabase.from('products').select('*', { count: 'exact', head: true });
  console.log(`Total products now in database: ${count}`);
}

