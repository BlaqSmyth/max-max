import { createClient } from '@supabase/supabase-js';
import { readFileSync } from 'fs';

const supabase = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_KEY);

const existingNames = new Set(JSON.parse(readFileSync('/tmp/existing_names_v2.json', 'utf8')));

function exists(name) {
  return existingNames.has(name.toLowerCase().trim());
}

let idCounter = 0;
function p(name, category, price, description = '') {
  if (exists(name)) return null;
  idCounter++;
  return {
    id: 'inv2-' + name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-+$/, '').substring(0, 55) + '-' + idCounter,
    name,
    description: description || name,
    category,
    price: price.toFixed(2),
    member_price: null,
    image: '/placeholder-product.png',
    in_stock: 1,
  };
}

